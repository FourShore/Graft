import { globToRegExp, type ChangeRecord, type CommandEvidence, type Evidence } from "@fourshore/graft-core";
import type { DiffFile } from "./diff.js";

/**
 * How a reviewer should spend attention on a file. Behavior changes get read;
 * tests get skimmed; mechanical changes get collapsed. The rules are
 * heuristics on paths and content and are listed in the UI, not hidden.
 */
export type FileGroup = "behavior" | "tests" | "mechanical";

const TEST_PATH = /(^|\/)(tests?|__tests__|spec|specs|fixtures)(\/|$)|\.(test|spec)\.[cm]?[jt]sx?$|_test\.(go|py|rb)$|(^|\/)test_[^/]+\.py$|Test\.(java|kt|cs)$/;
const MECHANICAL_PATH =
  /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Cargo\.lock|go\.sum|poetry\.lock|Gemfile\.lock|composer\.lock)$|\.(snap|min\.js|min\.css|map|lock)$|(^|\/)(vendor|node_modules|generated|__snapshots__)\/|\.(md|mdx|txt|rst)$|(^|\/)(LICENSE|CHANGELOG|NOTICE)([.-][^/]*)?$/;
/** Build output only at the root or in a first-level workspace package, so `src/build/auth.ts` is not waved through. */
const OUTPUT_DIR = /^(?:(?:packages|apps|libs|services)\/[^/]+\/)?(dist|build|out)\//;
const GENERATED_MARK = /@generated|DO NOT EDIT|Code generated by|This file is auto-?generated/i;
/** How far into a file a generated marker counts: the header, not anywhere a diff's context happens to show. */
const MARK_LINES = 5;

const STRICTNESS: FileGroup[] = ["mechanical", "tests", "behavior"];

/**
 * `behaviorFiles` are policy globs (same rules as secretFiles) naming files
 * that are behavior whatever the heuristics say, such as a schema kept in
 * Markdown. They are checked first. A renamed file is grouped by its old and
 * its new path and takes the stricter group, so moving `src/auth.ts` to
 * `docs/auth.md` is still behavior.
 */
export function groupFile(file: DiffFile, behaviorFiles: string[] = []): FileGroup {
  const paths = file.oldPath !== undefined && file.oldPath !== file.path ? [file.path, file.oldPath] : [file.path];
  const groups = paths.map((p) => groupPath(p, file, behaviorFiles));
  return groups.reduce((a, b) => (STRICTNESS.indexOf(b) > STRICTNESS.indexOf(a) ? b : a));
}

function groupPath(path: string, file: DiffFile, behaviorFiles: string[]): FileGroup {
  if (behaviorFiles.some((g) => globToRegExp(g).test(path))) return "behavior";
  if (TEST_PATH.test(path)) return "tests";
  if (MECHANICAL_PATH.test(path) || OUTPUT_DIR.test(path)) return "mechanical";
  if (GENERATED_MARK.test(fileHead(file))) return "mechanical";
  return "behavior";
}

/** The first lines of the new file, when the diff shows them: from a hunk that starts at line 1. */
function fileHead(file: DiffFile): string {
  const first = file.hunks.find((h) => /^@@ -\S+ \+1(,\d+)? @@/.test(h.header));
  if (!first) return "";
  return first.lines
    .filter((l) => l.kind === "add" || l.kind === "context")
    .slice(0, MARK_LINES)
    .map((l) => l.text)
    .join("\n");
}

const TEST_COMMAND =
  /\b(vitest|jest|mocha|ava|tap|pytest|unittest|nose2?|rspec|minitest|phpunit|cargo test|go test|dotnet test|gradle(w)? test|mvn (test|verify)|npm (run )?test|pnpm test|yarn test|bun test|make test|ctest)\b/;

export interface EvidenceVerdict {
  /** Commands that look like test runs. */
  testRuns: CommandEvidence[];
  /** True when at least one test run exists and the latest one passed. */
  testsPassed: boolean;
  /** Any command evidence that failed (shown so a reviewer sees the trail). */
  failures: CommandEvidence[];
  notes: number;
}

export function judgeEvidence(evidence: Evidence[]): EvidenceVerdict {
  const cmds = evidence.filter((e): e is CommandEvidence => e.kind === "command");
  const testRuns = cmds.filter((c) => TEST_COMMAND.test(c.command) || /test/i.test(c.label ?? ""));
  const last = testRuns.at(-1);
  return {
    testRuns,
    testsPassed: Boolean(last && last.exitCode === 0 && !last.stale),
    failures: cmds.filter((c) => c.exitCode !== 0),
    notes: evidence.filter((e) => e.kind === "note").length,
  };
}

/**
 * The one word a reviewer reads first.
 *   read:       behavior or tests changed and no test run passed
 *   tested:     behavior or tests changed and the latest test run passed;
 *               a command exited 0, not proof that a test covered the change
 *   mechanical: only docs, lockfiles or generated files changed
 *   partial:    the commit has Graft trailers but neither the note nor an
 *               Evidence: block in its message, so the evidence cannot be
 *               inspected (commits landed before 0.0.6 with no note here)
 *   unrecorded: commit has no change record at all
 */
export type Risk = "read" | "tested" | "mechanical" | "partial" | "unrecorded";

export interface Triage {
  risk: Risk;
  groups: Record<FileGroup, DiffFile[]>;
  verdict: EvidenceVerdict;
}

export function triage(
  record: ChangeRecord | null,
  files: DiffFile[],
  trailers: Record<string, string> = {},
  source: "note" | "message" | null = record ? "note" : null,
  behaviorFiles: string[] = [],
): Triage {
  const groups: Record<FileGroup, DiffFile[]> = { behavior: [], tests: [], mechanical: [] };
  for (const f of files) groups[groupFile(f, behaviorFiles)].push(f);
  const verdict = judgeEvidence(record?.evidence ?? []);
  const summaryOnly =
    source === "message" && record?.evidence.length === 0 && (trailers["Graft-Evidence"] ?? "none") !== "none";
  let risk: Risk;
  if (!record) risk = trailers["Graft-Change"] ? "partial" : "unrecorded";
  else if (summaryOnly) risk = "partial";
  // A commit that only edits tests can weaken them, so it is read like behavior, not collapsed.
  else if (groups.behavior.length === 0 && groups.tests.length === 0) risk = "mechanical";
  else if (verdict.testsPassed) risk = "tested";
  else risk = "read";
  return { risk, groups, verdict };
}

export const RISK_ORDER: Risk[] = ["read", "partial", "unrecorded", "tested", "mechanical"];
