import type { ChangeRecord, CommandEvidence, Evidence } from "@fourshore/graft-core";
import type { DiffFile } from "./diff.js";

/**
 * How a reviewer should spend attention on a file. Behavior changes get read;
 * tests get skimmed; mechanical changes get collapsed. The rules are
 * heuristics on paths and content and are listed in the UI, not hidden.
 */
export type FileGroup = "behavior" | "tests" | "mechanical";

const TEST_PATH = /(^|\/)(tests?|__tests__|spec|specs|fixtures)(\/|$)|\.(test|spec)\.[cm]?[jt]sx?$|_test\.(go|py|rb)$|(^|\/)test_[^/]+\.py$|Test\.(java|kt|cs)$/;
const MECHANICAL_PATH =
  /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Cargo\.lock|go\.sum|poetry\.lock|Gemfile\.lock|composer\.lock)$|\.(snap|min\.js|min\.css|map|lock)$|(^|\/)(dist|build|vendor|node_modules|generated|__snapshots__)\/|\.(md|mdx|txt|rst)$|(^|\/)(LICENSE|CHANGELOG|NOTICE)([.-][^/]*)?$/;
const GENERATED_MARK = /@generated|DO NOT EDIT|Code generated by|This file is auto-?generated/i;

export function groupFile(file: DiffFile): FileGroup {
  if (TEST_PATH.test(file.path)) return "tests";
  if (MECHANICAL_PATH.test(file.path)) return "mechanical";
  const head = file.hunks
    .flatMap((h) => h.lines)
    .slice(0, 30)
    .map((l) => l.text)
    .join("\n");
  if (GENERATED_MARK.test(head)) return "mechanical";
  return "behavior";
}

const TEST_COMMAND =
  /\b(vitest|jest|mocha|ava|tap|pytest|unittest|nose2?|rspec|minitest|phpunit|cargo test|go test|dotnet test|gradle(w)? test|mvn (test|verify)|npm (run )?test|pnpm test|yarn test|bun test|make test|ctest)\b/;

export interface EvidenceVerdict {
  /** Commands that look like test runs. */
  testRuns: CommandEvidence[];
  /** True when at least one test run exists and the latest one passed. */
  testsPassed: boolean;
  /** Any command evidence that failed (shown so a reviewer sees the trail). */
  failures: CommandEvidence[];
  notes: number;
}

export function judgeEvidence(evidence: Evidence[]): EvidenceVerdict {
  const cmds = evidence.filter((e): e is CommandEvidence => e.kind === "command");
  const testRuns = cmds.filter((c) => TEST_COMMAND.test(c.command) || /test/i.test(c.label ?? ""));
  const last = testRuns.at(-1);
  return {
    testRuns,
    testsPassed: Boolean(last && last.exitCode === 0),
    failures: cmds.filter((c) => c.exitCode !== 0),
    notes: evidence.length - cmds.length,
  };
}

/**
 * The one word a reviewer reads first.
 *   read:       behavior changed and nothing proves it works
 *   verified:   behavior changed and a test run passed
 *   mechanical: no behavior files changed
 *   partial:    the commit has Graft trailers but neither the note nor an
 *               Evidence: block in its message, so the evidence cannot be
 *               inspected (commits landed before 0.0.6 with no note here)
 *   unrecorded: commit has no change record at all
 */
export type Risk = "read" | "verified" | "mechanical" | "partial" | "unrecorded";

export interface Triage {
  risk: Risk;
  groups: Record<FileGroup, DiffFile[]>;
  verdict: EvidenceVerdict;
}

export function triage(
  record: ChangeRecord | null,
  files: DiffFile[],
  trailers: Record<string, string> = {},
  source: "note" | "message" | null = record ? "note" : null,
): Triage {
  const groups: Record<FileGroup, DiffFile[]> = { behavior: [], tests: [], mechanical: [] };
  for (const f of files) groups[groupFile(f)].push(f);
  const verdict = judgeEvidence(record?.evidence ?? []);
  const summaryOnly =
    source === "message" && record?.evidence.length === 0 && (trailers["Graft-Evidence"] ?? "none") !== "none";
  let risk: Risk;
  if (!record) risk = trailers["Graft-Change"] ? "partial" : "unrecorded";
  else if (summaryOnly) risk = "partial";
  else if (groups.behavior.length === 0) risk = "mechanical";
  else if (verdict.testsPassed) risk = "verified";
  else risk = "read";
  return { risk, groups, verdict };
}

export const RISK_ORDER: Risk[] = ["read", "partial", "unrecorded", "verified", "mechanical"];
