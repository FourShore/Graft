import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Graft } from "@fourshore/graft-core";
import { beforeEach, describe, expect, it } from "vitest";
import { parseDiff } from "../src/diff.js";
import { Review, createReviewServer } from "../src/index.js";
import { renderCheckGithub, renderCheckText, runCheck } from "../src/check.js";
import { groupFile, judgeEvidence, triage } from "../src/triage.js";

let dir: string;
let graft: Graft;
const sh = (args: string[], cwd = dir, input?: string) =>
  execFileSync("git", args, { cwd, encoding: "utf8", input }).trim();

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "graft-review-"));
  sh(["init", "-q", "-b", "main"]);
  sh(["config", "user.name", "Test"]);
  sh(["config", "user.email", "test@example.com"]);
  graft = new Graft(dir);
});

const SAMPLE = `diff --git a/src/a.ts b/src/a.ts
index 1111111..2222222 100644
--- a/src/a.ts
+++ b/src/a.ts
@@ -1,3 +1,4 @@
 const a = 1;
-const b = 2;
+const b = 3;
+const c = 4;
 export { a, b };
diff --git a/old.txt b/new.txt
similarity index 100%
rename from old.txt
rename to new.txt
diff --git a/img.png b/img.png
new file mode 100644
Binary files /dev/null and b/img.png differ
`;

describe("parseDiff", () => {
  it("reads files, hunks, renames, binaries and counts", () => {
    const files = parseDiff(SAMPLE);
    expect(files.map((f) => f.path)).toEqual(["src/a.ts", "new.txt", "img.png"]);
    expect(files[0].additions).toBe(2);
    expect(files[0].deletions).toBe(1);
    expect(files[0].hunks[0].lines.map((l) => l.kind)).toEqual(["context", "del", "add", "add", "context"]);
    expect(files[1]).toMatchObject({ status: "renamed", oldPath: "old.txt" });
    expect(files[2].status).toBe("binary");
  });
});

describe("grouping", () => {
  const file = (path: string, text = "") => ({
    path,
    status: "modified" as const,
    hunks: [{ header: "@@", lines: [{ kind: "add" as const, text }] }],
    additions: 1,
    deletions: 0,
  });
  it("classifies by path and generated markers", () => {
    expect(groupFile(file("src/server.ts"))).toBe("behavior");
    expect(groupFile(file("src/server.test.ts"))).toBe("tests");
    expect(groupFile(file("tests/e2e/login.py"))).toBe("tests");
    expect(groupFile(file("package-lock.json"))).toBe("mechanical");
    expect(groupFile(file("README.md"))).toBe("mechanical");
    expect(groupFile(file("dist/bundle.js"))).toBe("mechanical");
    expect(groupFile(file("src/schema.ts", "// @generated by protoc"))).toBe("mechanical");
  });
});

describe("evidence judgement", () => {
  it("recognises test runs and uses the last one", () => {
    const v = judgeEvidence([
      { kind: "command", at: "", command: "npm test", exitCode: 1, durationMs: 1, output: "" },
      { kind: "command", at: "", command: "npm test", exitCode: 0, durationMs: 1, output: "" },
      { kind: "command", at: "", command: "npm run build", exitCode: 0, durationMs: 1, output: "" },
      { kind: "note", at: "", text: "checked" },
    ]);
    expect(v.testRuns).toHaveLength(2);
    expect(v.testsPassed).toBe(true);
    expect(v.failures).toHaveLength(1);
    expect(v.notes).toBe(1);
  });

  it("does not count a build as a test", () => {
    const v = judgeEvidence([{ kind: "command", at: "", command: "npm run build", exitCode: 0, durationMs: 1, output: "" }]);
    expect(v.testsPassed).toBe(false);
  });
});

describe("triage", () => {
  const behavior = parseDiff(SAMPLE);
  const record = (evidence: Parameters<typeof judgeEvidence>[0]) => ({
    version: 1 as const,
    id: "x".repeat(20),
    task: "t",
    author: { kind: "agent" as const, name: "a" },
    startedAt: "",
    evidence,
  });
  it("needs reading when behavior changed with no passing tests", () => {
    expect(triage(record([{ kind: "note", at: "", text: "looked" }]), behavior).risk).toBe("read");
  });
  it("is verified when a test run passed", () => {
    expect(triage(record([{ kind: "command", at: "", command: "pytest", exitCode: 0, durationMs: 1, output: "" }]), behavior).risk).toBe("verified");
  });
  it("is mechanical when no behavior files changed", () => {
    const docsOnly = "diff --git" + SAMPLE.split("diff --git")[1];
    const docs = parseDiff(docsOnly.replaceAll("src/a.ts", "docs/a.md"));
    expect(triage(record([]), docs).risk).toBe("mechanical");
  });
  it("is unrecorded without a record", () => {
    expect(triage(null, behavior).risk).toBe("unrecorded");
  });
  it("treats policy behaviorFiles as behavior whatever the path says", () => {
    const docsOnly = "diff --git" + SAMPLE.split("diff --git")[1];
    const docs = parseDiff(docsOnly.replaceAll("src/a.ts", "docs/platinum-schema.md"));
    expect(triage(record([]), docs, {}, "note", ["docs/*.md"]).risk).toBe("read");
    expect(triage(record([]), docs, {}, "note", ["specs/**"]).risk).toBe("mechanical");
  });
});

describe("Review over a real repo", () => {
  it("queues changes by risk and serves pages", async () => {
    await writeFile(join(dir, "README.md"), "# hi\n");
    sh(["add", "-A"]);
    sh(["commit", "-q", "-m", "plain docs commit"]);

    await graft.start({ task: "risky change", author: { kind: "agent", name: "bot" } });
    await mkdir(join(dir, "src"), { recursive: true });
    await writeFile(join(dir, "src/app.ts"), "export const x = 1;\n");
    await graft.evidenceNote("eyeballed it");
    const risky = await graft.land({ all: true });

    await graft.start({ task: "safe change", author: { kind: "agent", name: "bot" } });
    await writeFile(join(dir, "src/app.ts"), "export const x = 2;\n");
    await graft.evidenceCommand("true", "unit tests");
    const safe = await graft.land({ all: true });

    const review = new Review({ repo: dir });
    const q = await review.queue();
    expect(q.map((i) => i.triage.risk)).toEqual(["read", "unrecorded", "verified"]);
    expect(q[0].entry.commit).toBe(risky.commit);
    expect(q[2].entry.commit).toBe(safe.commit);

    const server = createReviewServer({ repo: dir });
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    const port = (server.address() as AddressInfo).port;
    try {
      const home = await fetch(`http://127.0.0.1:${port}/`);
      expect(home.status).toBe(200);
      const homeText = await home.text();
      expect(homeText).toContain("risky change");
      expect(homeText).toContain("Needs reading");
      expect(homeText.indexOf("risky change")).toBeLessThan(homeText.indexOf("safe change"));

      const page = await fetch(`http://127.0.0.1:${port}/change/${safe.commit}`);
      expect(page.status).toBe(200);
      const pageText = await page.text();
      expect(pageText).toContain("safe change");
      expect(pageText).toContain("Verified");
      expect(pageText).toContain("src/app.ts");
      expect(pageText).toContain("+export const x = 2;");
      expect(pageText).toContain("unit tests");

      const api = await fetch(`http://127.0.0.1:${port}/api/change/${risky.record.id}`);
      expect(api.status).toBe(200);
      const body = (await api.json()) as { triage: { risk: string } };
      expect(body.triage.risk).toBe("read");

      expect((await fetch(`http://127.0.0.1:${port}/change/nope`)).status).toBe(404);
    } finally {
      await new Promise<void>((r) => server.close(() => r()));
    }
  });

  it("reads the evidence list from the commit message when the note is missing", async () => {
    await graft.start({ task: "note went missing", author: { kind: "agent", name: "bot" } });
    await writeFile(join(dir, "x.ts"), "export const y = 1;\n");
    await graft.evidenceCommand("true", "unit tests");
    const { commit } = await graft.land({ all: true });
    sh(["notes", "--ref=refs/notes/graft", "remove", commit]);

    const review = new Review({ repo: dir });
    const [item] = await review.queue();
    expect(item.triage.risk).toBe("verified");
    expect(item.entry.recordSource).toBe("message");

    const server = createReviewServer({ repo: dir });
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    const port = (server.address() as AddressInfo).port;
    try {
      const home = await (await fetch(`http://127.0.0.1:${port}/`)).text();
      expect(home).toContain("Verified");
      expect(home).toContain("tests passed · 1 evidence, note missing");
      const page = await (await fetch(`http://127.0.0.1:${port}/change/${commit}`)).text();
      expect(page).toContain("agent:bot");
      expect(page).toContain("unit tests");
      expect(page).toContain("output not in this clone");
      expect(page).toContain("graft sync");
    } finally {
      await new Promise<void>((r) => server.close(() => r()));
    }
  });

  it("reads behaviorFiles from the repo's policy", async () => {
    await mkdir(join(dir, ".graft"), { recursive: true });
    await writeFile(join(dir, ".graft/policy.json"), JSON.stringify({ version: 1, requireEvidence: false, behaviorFiles: ["schema.md"] }));
    await mkdir(join(dir, "docs"), { recursive: true });
    await writeFile(join(dir, "docs/schema.md"), "# schema\n");
    await graft.start({ task: "schema change" });
    await graft.land({ all: true });
    const [item] = await new Review({ repo: dir }).queue();
    expect(item.triage.groups.behavior.map((f) => f.path)).toContain("docs/schema.md");
    expect(item.triage.groups.mechanical).toEqual([]);
    expect(item.triage.risk).toBe("read");
  });

  it("falls back to the trailer summary when the message has no evidence list", async () => {
    await writeFile(join(dir, "x.ts"), "export const y = 1;\n");
    sh(["add", "-A"]);
    sh([
      "commit",
      "-q",
      "-F",
      "-",
    ], dir, "old style\n\nGraft-Change: m4z1gs7jgdyp3pj2za9c\nGraft-Task: old style\nGraft-Author: agent:bot\nGraft-Evidence: 1 command, 1 passed\n");
    const commit = sh(["rev-parse", "HEAD"]);

    const review = new Review({ repo: dir });
    const [item] = await review.queue();
    expect(item.triage.risk).toBe("partial");

    const server = createReviewServer({ repo: dir });
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    const port = (server.address() as AddressInfo).port;
    try {
      const home = await (await fetch(`http://127.0.0.1:${port}/`)).text();
      expect(home).toContain("Note missing");
      expect(home).toContain("1 command, 1 passed (summary only)");
      const page = await (await fetch(`http://127.0.0.1:${port}/change/${commit}`)).text();
      expect(page).toContain("graft sync");
    } finally {
      await new Promise<void>((r) => server.close(() => r()));
    }
  });

  it("escapes HTML in tasks and diffs", async () => {
    await graft.start({ task: "<script>alert(1)</script>", author: { kind: "agent", name: "bot" } });
    await writeFile(join(dir, "x.ts"), "const s = '<b>';\n");
    await graft.evidenceNote("ok");
    await graft.land({ all: true });
    const server = createReviewServer({ repo: dir });
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    const port = (server.address() as AddressInfo).port;
    try {
      const text = await (await fetch(`http://127.0.0.1:${port}/`)).text();
      expect(text).not.toContain("<script>alert");
      expect(text).toContain("&lt;script&gt;");
    } finally {
      await new Promise<void>((r) => server.close(() => r()));
    }
  });
});

describe("check", () => {
  async function seed() {
    await mkdir(join(dir, "src"), { recursive: true });
    await writeFile(join(dir, "src", "a.ts"), "export const a = 1;\n");
    await writeFile(join(dir, "README.md"), "hi\n");
    sh(["add", "-A"]);
    sh(["commit", "-q", "-m", "base"]);
    const base = sh(["rev-parse", "HEAD"]);
    return base;
  }

  it("passes a branch whose behavior commits carry passing commands, re-runs them, and lets mechanical commits through", async () => {
    const base = await seed();
    await graft.start({ task: "change a" });
    await writeFile(join(dir, "src", "a.ts"), "export const a = 2;\n");
    await graft.evidenceCommand("npm test", "unit tests"); // fails: no package.json, exit code non-zero
    await graft.evidenceCommand("echo verified", "unit tests");
    await graft.land({ all: true });
    await writeFile(join(dir, "README.md"), "docs only\n");
    sh(["commit", "-q", "-am", "docs tweak"]);

    const r = await runCheck({ repo: dir, base, rerun: true });
    expect(r.commits.map((c) => [c.entry.title, c.triage.risk, c.ok])).toEqual([
      ["docs tweak", "unrecorded", true],
      ["change a", "verified", true],
    ]);
    expect(r.reruns).toMatchObject([{ command: "echo verified", exitCode: 0 }]);
    expect(r.findings).toEqual([]);
    expect(r.ok).toBe(true);
    const text = renderCheckText(r);
    expect(text).toContain("ok   ");
    expect(text).toContain("Re-ran 1 recorded command");
    expect(text).toMatch(/PASS:/);
  });

  it("fails behavior changes without a record, without evidence under policy, and when a recorded command no longer passes", async () => {
    const base = await seed();
    await mkdir(join(dir, ".graft"), { recursive: true });
    await writeFile(join(dir, ".graft/policy.json"), JSON.stringify({ version: 1, requireEvidence: "command" }));
    // 1: behavior change with no record at all
    await writeFile(join(dir, "src", "a.ts"), "export const a = 2;\n");
    sh(["commit", "-q", "-am", "plain edit"]);
    // 2: record with notes only
    await graft.start({ task: "note only" });
    await writeFile(join(dir, "src", "a.ts"), "export const a = 3;\n");
    await graft.evidenceNote("looked");
    await graft.land({ all: true, allowNoEvidence: true });
    // 3: a command that passed then but fails now
    await graft.start({ task: "flaky" });
    await writeFile(join(dir, "src", "a.ts"), "export const a = 4;\n");
    await writeFile(join(dir, "gate"), "");
    await graft.evidenceCommand("test -f gate", "gate present");
    await graft.land({ all: true });
    sh(["rm", "-q", "gate"]);
    sh(["commit", "-q", "-m", "remove gate"]); // also unrecorded, and "gate" counts as behavior

    const r = await runCheck({ repo: dir, base, rerun: true });
    expect(r.ok).toBe(false);
    expect(r.findings.map((f) => f.kind).sort()).toEqual(["no-passing-command", "no-record", "no-record", "rerun-failed"]);
    const text = renderCheckText(r);
    expect(text).toContain('"plain edit" changed src/a.ts with no change record');
    expect(text).toContain('policy requireEvidence: "command"');
    expect(text).toContain('"test -f gate" was recorded as passing');
    expect(text).toMatch(/FAIL: see findings/);
    const gh = renderCheckGithub(r);
    expect(gh.annotations).toHaveLength(4);
    expect(gh.annotations[0]).toMatch(/^::error title=Graft check::/);
    expect(gh.summary).toContain("### Graft check: fail");
    expect(gh.summary).toContain("| ❌ |");
  });

  it("re-runs only commands allowed by checkCommands and reports the rest as skipped without failing", async () => {
    const base = await seed();
    await mkdir(join(dir, ".graft"), { recursive: true });
    await writeFile(join(dir, ".graft/policy.json"), JSON.stringify({ version: 1, requireEvidence: true, checkCommands: ["^echo "] }));
    await graft.start({ task: "x" });
    await writeFile(join(dir, "src", "a.ts"), "export const a = 9;\n");
    await graft.evidenceCommand("echo fine");
    await graft.evidenceCommand("true");
    await graft.land({ all: true });
    const r = await runCheck({ repo: dir, base, rerun: true });
    expect(r.reruns.map((x) => x.command)).toEqual(["echo fine"]);
    expect(r.findings).toMatchObject([{ kind: "rerun-skipped", command: "true" }]);
    expect(r.ok).toBe(true);
  });

  it("is empty and passing when the branch has no commits past the base", async () => {
    const base = await seed();
    const r = await runCheck({ repo: dir, base });
    expect(r.commits).toEqual([]);
    expect(r.ok).toBe(true);
  });
});
