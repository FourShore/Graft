describe("GitHub output", () => {
  it("escapes annotation messages and titles so they cannot end the command or start another", () => {
    expect(escapeGithubData("50% done\r\n::error::forged")).toBe("50%25 done%0D%0A::error::forged");
    expect(escapeGithubProperty("a: b, c%\n")).toBe("a%3A b%2C c%25%0A");
  });

  const cli = join(process.cwd(), "packages", "cli", "dist", "cli.js");
  const graftCli = (args: string[]) =>
    spawnSync("node", [cli, ...args], { cwd: dir, encoding: "utf8", env: { ...process.env, GITHUB_STEP_SUMMARY: "", GRAFT_CHECK_RERUN: "" } });

  it("wraps the text, which carries other people's output, in stop-commands", async () => {
    if (!existsSync(cli)) return; // needs a build; npm test runs after npm run build
    await writeFile(join(dir, "a.ts"), "1\n");
    sh(["add", "-A"]);
    sh(["commit", "-q", "-m", "base"]);
    await writeFile(join(dir, "a.ts"), "2\n");
    sh(["commit", "-q", "-am", "::error::forged"]);
    const r = graftCli(["check", "--base", "HEAD~1", "--format", "github"]);
    expect(r.status).toBe(1);
    const lines = r.stdout.split("\n");
    const stop = lines.findIndex((l) => /^::stop-commands::[0-9a-f]{32}$/.test(l));
    expect(stop).toBeGreaterThan(0);
    expect(lines[0]).toMatch(/^::error title=Graft check::/);
    const token = lines[stop].slice("::stop-commands::".length);
    const resume = lines.indexOf(`::${token}::`);
    expect(resume).toBeGreaterThan(stop);
    expect(lines.slice(stop, resume).some((l) => l.includes("::error::forged"))).toBe(true);
  });

  it("asks for --base rather than falling back to the branch's own upstream", async () => {
    if (!existsSync(cli)) return;
    const remote = await mkdtemp(join(tmpdir(), "graft-remote-"));
    execFileSync("git", ["init", "-q", "--bare", remote]);
    sh(["remote", "add", "origin", remote]);
    await writeFile(join(dir, "a.ts"), "1\n");
    sh(["add", "-A"]);
    sh(["commit", "-q", "-m", "base"]);
    sh(["checkout", "-q", "-b", "feature"]);
    sh(["push", "-q", "-u", "origin", "feature"]);
    const r = graftCli(["check"]);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("neither origin/main nor origin/master exists): pass --base <ref>");
  });
});
